#!/usr/bin/env python3
"""Gate and squash-merge open ingest PRs.

Scheduled and `workflow_run`-triggered coordinator that dispatches the three
validation gates on each open `auto/<x>-ingest` PR branch (the
`pull_request` runs of GITHUB_TOKEN-opened PRs wait for manual approval)
and squash-merges the PR once all three gates pass on its head commit.
A PR whose branch predates a change on main is regenerated by its ingest
workflow first, so the tested head is what lands.

PRs that fail a gate stay open with a comment linking the failed runs;
the next ingest run regenerates them.

Run from the repo root:

    GH_REPO=<owner>/<repo> GH_TOKEN=<token> python scripts/merge_ingest_prs.py

`--dry-run` prints the mutating `gh` calls instead of executing them.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass

GATES = ("validate-events.yml", "validate-templates.yml", "validate-ingesters.yml")
DATA_FILES = frozenset({"_data/special_events.yml"})
BRANCH = re.compile(r"^auto/([a-z0-9-]+)-ingest$")
BOT = "app/github-actions"  # author.login that `gh pr list` reports for github-actions[bot]
MARKER = "<!-- merge-ingest-prs:{sha} -->"

PR_FIELDS = "number,title,headRefName,headRefOid,author,isDraft,isCrossRepository,files"
RUN_FIELDS = "databaseId,headSha,status,conclusion,url,createdAt"


@dataclass(frozen=True)
class Decision:
    action: str
    detail: tuple = ()


def ingest_workflow(branch):
    """Return the ingest workflow filename for an ingest branch, else None."""
    m = BRANCH.match(branch)
    return f"ingest-{m.group(1)}.yml" if m else None


def latest_run(runs, sha):
    """Newest run (list is newest-first) whose headSha matches `sha`."""
    for run in runs:
        if run.get("headSha") == sha:
            return run
    return None


def decide(pr, main_changes, runs, workflows):
    """Classify an ingest PR's next coordinator action.

    pr: `gh pr list --json <PR_FIELDS>` item.
    main_changes: files changed on main since the merge base.
    runs: {gate: latest_run or None} keyed by gate workflow filename.
    workflows: filenames present in .github/workflows.
    """
    if (
        pr.get("isDraft")
        or pr.get("isCrossRepository")
        or (pr.get("author") or {}).get("login") != BOT
        or not BRANCH.match(pr.get("headRefName") or "")
        or not (pr.get("title") or "").startswith("Auto-ingest:")
    ):
        return Decision("skip", ("not an ingest PR",))

    paths = tuple(f.get("path") for f in (pr.get("files") or []))
    if not paths:
        return Decision("skip", ("no changed files",))
    if not set(paths) <= DATA_FILES:
        return Decision("skip", tuple(sorted(set(paths) - DATA_FILES)))

    if main_changes:
        workflow = ingest_workflow(pr["headRefName"])
        if workflow in workflows:
            return Decision("regenerate", (workflow,))
        return Decision("skip", (f"{workflow} not in .github/workflows",))

    missing = tuple(g for g in GATES if runs.get(g) is None)
    if missing:
        return Decision("dispatch", missing)

    incomplete = tuple(runs[g] for g in GATES if runs[g].get("status") != "completed")
    if incomplete:
        return Decision("wait", incomplete)

    failed = tuple(runs[g] for g in GATES if runs[g].get("conclusion") != "success")
    if failed:
        return Decision("report", failed)

    return Decision("merge")


def report_body(sha, failed_runs):
    lines = [
        MARKER.format(sha=sha),
        f"Automatic merge is on hold: these gates did not pass on `{sha[:7]}`:",
    ]
    for run in failed_runs:
        lines.append(
            f"- {run.get('name') or run.get('workflow')}: {run.get('url')}"
            f" ({run.get('conclusion')})"
        )
    lines.append(
        "This PR stays open until a fix lands on this branch or the next "
        "ingest run regenerates it."
    )
    return "\n".join(lines) + "\n"


def _is_read_only(args):
    if not args:
        return True
    if args[0] == "api":
        return True
    if args[0] == "pr":
        return args[1:2] in (["list"], ["view"])
    if args[0] == "run" and args[1:2] == ["list"]:
        return True
    if args[0] == "workflow" and args[1:2] in (["list"], ["view"]):
        return True
    return False


def gh(args, dry_run=False):
    """Run a gh CLI call and return stdout (empty for mutating calls)."""
    cmd = ["gh"] + args
    if dry_run and not _is_read_only(args):
        print("DRY RUN:", " ".join(cmd))
        return ""
    result = subprocess.run(cmd, check=True, capture_output=True, text=True)
    return result.stdout


def gh_json(args, dry_run=False):
    return json.loads(gh(args, dry_run=dry_run))


def log(msg, summary_file=None):
    print(msg, flush=True)
    if summary_file:
        summary_file.write(msg + "\n")
        summary_file.flush()


def _open_summary():
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    return open(path, "a") if path else None


def main(argv=None, gh_call=None, sleep=time.sleep):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--timeout-minutes", type=float, default=40)
    parser.add_argument("--poll-seconds", type=float, default=20)
    args = parser.parse_args(argv)

    dry_run = args.dry_run
    if gh_call is None:
        def gh_call(a):
            out = gh(a, dry_run=dry_run)
            return json.loads(out) if out.strip() else None
    deadline = time.monotonic() + args.timeout_minutes * 60
    workflows_dir = os.path.join(
        os.path.dirname(__file__), os.pardir, ".github", "workflows"
    )
    workflows = {
        f for f in os.listdir(workflows_dir) if f.endswith((".yml", ".yaml"))
    }
    summary = _open_summary()
    merged_any = False
    dispatched = set()  # (gate, sha) already dispatched this coordinator run
    try:
        prs = gh_call(
            ["pr", "list", "--state", "open", "--limit", "100", "--json", PR_FIELDS]
        )
        for pr in prs:
            number = pr["number"]
            branch = pr.get("headRefName") or ""
            sha = pr.get("headRefOid") or ""
            while True:
                if time.monotonic() > deadline:
                    log(f"#{number} timed out waiting for gates", summary)
                    break
                view = gh_call(
                    ["pr", "view", str(number), "--json", "headRefOid,state"]
                )
                if view.get("state") != "OPEN":
                    log(f"#{number} no longer open", summary)
                    break
                if view.get("headRefOid") != sha:
                    log(
                        f"#{number} head moved {sha[:7]} -> "
                        f"{str(view.get('headRefOid'))[:7]}, re-evaluating next pass",
                        summary,
                    )
                    break
                compare = gh_call(
                    [
                        "api",
                        f"repos/{{owner}}/{{repo}}/compare/{sha}...main",
                        "--jq", "[.files[].filename]",
                    ]
                )
                runs = {}
                for gate in GATES:
                    gate_runs = gh_call(
                        [
                            "run", "list",
                            "--workflow", gate,
                            "--branch", branch,
                            "--event", "workflow_dispatch",
                            "--limit", "20",
                            "--json", RUN_FIELDS,
                        ]
                    )
                    for run in gate_runs:
                        run.setdefault("workflow", gate)
                    runs[gate] = latest_run(gate_runs, sha)
                    if runs[gate] is None and (gate, sha) in dispatched:
                        runs[gate] = {
                            "headSha": sha,
                            "status": "dispatched",
                            "workflow": gate,
                        }
                decision = decide(pr, compare, runs, workflows)
                if decision.action == "skip":
                    log(f"#{number} skip: {', '.join(decision.detail)}", summary)
                    break
                if decision.action == "dispatch":
                    for gate in decision.detail:
                        gh_call(["workflow", "run", gate, "--ref", branch])
                        dispatched.add((gate, sha))
                        log(f"#{number} dispatched {gate} on {sha[:7]}", summary)
                    if dry_run:
                        break
                    continue
                if decision.action == "wait":
                    waiting = ", ".join(
                        f"{r.get('workflow')}:{r.get('status')}"
                        for r in decision.detail
                    )
                    log(f"#{number} waiting for gates ({waiting})", summary)
                    sleep(args.poll_seconds)
                    continue
                if decision.action == "regenerate":
                    workflow = decision.detail[0]
                    newest = gh_call(
                        ["run", "list", "--workflow", workflow, "--limit", "1",
                         "--json", "status"]
                    )
                    if newest and newest[0].get("status") in ("queued", "in_progress"):
                        log(f"#{number} {workflow} already running; skipping", summary)
                    else:
                        gh_call(["workflow", "run", workflow, "--ref", "main"])
                        log(f"#{number} regenerate: {workflow} on main", summary)
                    break
                if decision.action == "report":
                    marker = MARKER.format(sha=sha)
                    comments = gh_call(
                        ["pr", "view", str(number), "--json", "comments"]
                    ).get("comments", [])
                    if any(marker in (c.get("body") or "") for c in comments):
                        log(
                            f"#{number} already reported gate failure on {sha[:7]}",
                            summary,
                        )
                    else:
                        body = report_body(sha, decision.detail)
                        with tempfile.NamedTemporaryFile(
                            "w", suffix=".md", delete=False
                        ) as fh:
                            fh.write(body)
                            fname = fh.name
                        try:
                            gh_call(["pr", "comment", str(number), "--body-file", fname])
                        finally:
                            os.unlink(fname)
                        for run in decision.detail:
                            log(
                                f"#{number} report: {run.get('workflow')} "
                                f"{run.get('conclusion')} {run.get('url')}",
                                summary,
                            )
                    break
                if decision.action == "merge":
                    gh_call(
                        ["pr", "merge", str(number), "--squash",
                         "--match-head-commit", sha]
                    )
                    log(f"#{number} merged at {sha[:7]}", summary)
                    merged_any = True
                    break
        if merged_any:
            for gate in GATES:
                gh_call(["workflow", "run", gate, "--ref", "main"])
                log(f"dispatched {gate} on main", summary)
    finally:
        if summary:
            summary.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
